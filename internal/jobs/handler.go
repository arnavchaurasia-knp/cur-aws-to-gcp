func (h *Handler) Download(w http.ResponseWriter, r *http.Request) {
	sess := auth.SessionFromCtx(r.Context())
	id := chi.URLParam(r, "id")
	if !isValidJobID(id) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	job, err := h.db.GetJob(id)
	if err != nil {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if !h.canAccess(sess, job) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if job.Status != "done" {
		http.Error(w, `{"error":"report not ready"}`, http.StatusConflict)
		return
	}

	jobDir := filepath.Clean(filepath.Join(h.jobsDir, id))
	h.ensureJobDirRestored(r.Context(), id, jobDir)
	runIDParam := r.URL.Query().Get("run_id")
	format := r.URL.Query().Get("format")

	safeProspect := strings.Map(func(r rune) rune {
		switch r {
		case '"', '/', '\\', '\r', '\n', '\t':
			return '_'
		}
		return r
	}, job.Prospect)

	switch format {
	case "bill":
		inputMatches, _ := filepath.Glob(filepath.Join(jobDir, "input.*"))
		if len(inputMatches) == 0 {
			http.Error(w, `{"error":"original bill file not found"}`, http.StatusNotFound)
			return
		}
		billPath := inputMatches[0]
		ext := filepath.Ext(billPath)
		if strings.HasSuffix(billPath, ".csv.gz") {
			ext = ".csv.gz"
		}
		filename := fmt.Sprintf("%s-original-bill%s", safeProspect, ext)
		w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
		http.ServeFile(w, r, billPath)
	case "xlsx", "csv":
		h.downloadExport(w, r, jobDir, safeProspect, format)
	default:
		// HTML download (original behaviour)
		reportPath, runIDForFilename := resolveReportPath(jobDir, runIDParam)
		if reportPath == "" {
			http.Error(w, `{"error":"no report file found"}`, http.StatusNotFound)
			return
		}
		filename := fmt.Sprintf("%s-gcp-estimate.html", safeProspect)
		if runIDForFilename != "" {
			filename = fmt.Sprintf("%s-gcp-estimate-%s.html", safeProspect, runIDForFilename)
		}
		w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
		w.Header().Set("Content-Type", "text/html")
		http.ServeFile(w, r, reportPath)
	}
}

// downloadExport generates an XLSX or CSV export from the job's DuckDB via the
// export_report.py script and streams it back as an attachment.
func (h *Handler) downloadExport(w http.ResponseWriter, r *http.Request, jobDir, safeProspect, format string) {
	ext := "." + format
	tmpFile, err := os.CreateTemp("", "gcp-export-*"+ext)
	if err != nil {
		http.Error(w, `{"error":"could not create temp file"}`, http.StatusInternalServerError)
		return
	}
	tmpPath := tmpFile.Name()
	tmpFile.Close()
	defer os.Remove(tmpPath)

	scriptPath := filepath.Join(skill.ResolveDir(), "scripts", "export_report.py")
	dbPath := filepath.Join(jobDir, "projection-audit", "projection.duckdb")
	cmd := exec.Command(pythonBin(), scriptPath, "--format", format, "--db", dbPath, "--out", tmpPath)
	cmd.Dir = jobDir
	scriptsDir := filepath.Join(skill.ResolveDir(), "scripts")
	cmd.Env = append(os.Environ(), "PYTHONPATH="+scriptsDir)
	if out, err := cmd.CombinedOutput(); err != nil {
		http.Error(w, `{"error":"export failed: `+jsonEscape(string(out))+`"}`, http.StatusInternalServerError)
		return
	}

	filename := fmt.Sprintf("%s-gcp-estimate%s", safeProspect, ext)
	var contentType string
	if format == "xlsx" {
		contentType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
	} else {
		contentType = "text/csv; charset=utf-8"
	}
	w.Header().Set("Content-Type", contentType)
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
	http.ServeFile(w, r, tmpPath)
}

// resolveReportPath picks the report.html to serve for a Download request.
// Tries, in order:
//   1. Specific run_id from run_results (if runIDParam non-empty)
//   2. Latest row in run_results
//   3. projection-audit/report.html (legacy unsuffixed)
//   4. report.html at the job dir root (very old promotion-era jobs)
// Returns ("", "") if none of those exist on disk. The second return is
// the run_id used (empty for fallback paths) so the caller can embed it
// in Content-Disposition.
func resolveReportPath(jobDir, runIDParam string) (string, string) {
	dbPath := filepath.Join(jobDir, projectionAuditDir, projectionDuckDB)
	runs, _ := QueryRunResults(dbPath) // empty slice on missing db/table

	var pick *RunResult
	if runIDParam != "" {
		for i := range runs {
			if runs[i].RunID == runIDParam {
				pick = &runs[i]
				break
			}
		}
	} else if len(runs) > 0 {
		pick = &runs[0]
	}

	if pick != nil && pick.ReportHTML != nil && *pick.ReportHTML != "" {
		p := filepath.Join(jobDir, *pick.ReportHTML)
		if clean := filepath.Clean(p); !strings.HasPrefix(clean, jobDir+string(filepath.Separator)) {
			return "", ""
		}
		if _, err := os.Stat(p); err == nil {
			return p, pick.RunID
		}
	}
	// Fallback chain for legacy jobs (none of which we expect to keep
	// hitting once BackfillRunResults has covered all existing jobs).
	if p := filepath.Join(jobDir, projectionAuditDir, "report.html"); fileExists(p) {
		return p, ""
	}
	if p := filepath.Join(jobDir, "report.html"); fileExists(p) {
		return p, ""
	}
	return "", ""
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

var (
	reCardAWSMapped = regexp.MustCompile(`<div class="card-label">\s*AWS Mapped Cost\s*</div>\s*<div class="card-value">\s*([^<]+)\s*</div>`)
	reCardGCPOD     = regexp.MustCompile(`<div class="card-label">\s*GCP On-Demand\s*</div>\s*<div class="card-value">\s*([^<]+)\s*</div>`)
	reCardGCP1Yr    = regexp.MustCompile(`<div class="card-label">\s*GCP 1-Year CUD\s*</div>\s*<div class="card-value">\s*([^<]+)\s*</div>`)
	reCardGCP3Yr    = regexp.MustCompile(`<div class="card-label">\s*GCP 3-Year CUD\s*</div>\s*<div class="card-value">\s*([^<]+)\s*</div>`)
)

func parseCardCurrency(s string) (float64, bool) {
	var b strings.Builder
	for _, ch := range s {
		if (ch >= '0' && ch <= '9') || ch == '.' || ch == '-' {
			b.WriteRune(ch)
		}
	}
	v, err := strconv.ParseFloat(b.String(), 64)
	if err != nil {
		return 0, false
	}
	return v, true
}

func reconcileRunFromReportHTML(reportPath string, r *RunResult) {
	data, err := os.ReadFile(reportPath)
	if err != nil {
		return
	}
	content := string(data)
	if m := reCardAWSMapped.FindStringSubmatch(content); len(m) > 1 {
		if v, ok := parseCardCurrency(m[1]); ok {
			r.AWSTotal = &v
		}
	}
	if m := reCardGCPOD.FindStringSubmatch(content); len(m) > 1 {
		if v, ok := parseCardCurrency(m[1]); ok {
			r.GCPOD = &v
		}
	}
	if m := reCardGCP1Yr.FindStringSubmatch(content); len(m) > 1 {
		if v, ok := parseCardCurrency(m[1]); ok {
			r.GCP1yrCUD = &v
		}
	}
	if m := reCardGCP3Yr.FindStringSubmatch(content); len(m) > 1 {
		if v, ok := parseCardCurrency(m[1]); ok {
			r.GCP3yrCUD = &v
		}
	}
}

// Runs returns the run_results history for a job, latest first. Returns
// an empty array (not 404) when the job has no run_results yet — the job
// itself still exists, there's just no run history (very fresh job or
// pre-backfill legacy).
func (h *Handler) Runs(w http.ResponseWriter, r *http.Request) {
	sess := auth.SessionFromCtx(r.Context())
	id := chi.URLParam(r, "id")
	if !isValidJobID(id) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	job, err := h.db.GetJob(id)
	if err != nil {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if !h.canAccess(sess, job) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	jobDir := filepath.Clean(filepath.Join(h.jobsDir, id))
	h.ensureJobDirRestored(r.Context(), id, jobDir)
	dbPath := filepath.Join(jobDir, projectionAuditDir, projectionDuckDB)
	runs, err := QueryRunResults(dbPath)
	if err != nil {
		// Issue 6: err.Error() includes full filesystem path — log server-side only
		slog.Error("runs query failed", "job_id", id, "err", err)
		http.Error(w, `{"error":"internal error"}`, http.StatusInternalServerError)
		return
	}
	if runs == nil {
		runs = []RunResult{}
	} else {
		for i := range runs {
			reportPath, _ := resolveReportPath(jobDir, runs[i].RunID)
			if reportPath != "" {
				reconcileRunFromReportHTML(reportPath, &runs[i])
			}
		}
	}
	w.Header().Set(contentTypeHeader, contentTypeJSON)
	cur, _ := QueryBillCurrency(dbPath) // best-effort; defaults to USD on error
	json.NewEncoder(w).Encode(map[string]any{
		"runs":     runs,
		"currency": cur,
	})
}

