func (h *Handler) Retry(w http.ResponseWriter, r *http.Request) {
	sess := auth.SessionFromCtx(r.Context())
	id := chi.URLParam(r, "id")
	if !isValidJobID(id) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	job, err := h.db.GetJob(id)
	if err != nil {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if !h.canAccess(sess, job) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if job.Status != "failed" {
		http.Error(w, `{"error":"can only retry a failed job"}`, http.StatusConflict)
		return
	}

	jobDir := filepath.Clean(filepath.Join(h.jobsDir, id))
	h.ensureJobDirRestored(r.Context(), id, jobDir)

	// On ephemeral container hosts (e.g. Render free tier without persistent disk or S3),
	// a redeploy clears local storage. If input.* is missing, do not spawn a doomed run.
	inputMatches, _ := filepath.Glob(filepath.Join(jobDir, "input.*"))
	if len(inputMatches) == 0 {
		http.Error(w, `{"error":"Original input file is missing (server was restarted or redeployed). Please upload the bill again as a new report."}`, http.StatusBadRequest)
		return
	}

	// Legacy repair: if job was started with bare .gz but is a gzipped CSV, rename to .csv.gz
	for _, match := range inputMatches {
		base := filepath.Base(match)
		if base == "input.gz" {
			newPath := filepath.Join(jobDir, "input.csv.gz")
			if err := os.Rename(match, newPath); err == nil {
				job.InputExt = ".csv.gz"
			}
			break
		}
	}

	_ = os.Remove(filepath.Join(jobDir, "failure.txt"))
	_ = os.Remove(filepath.Join(jobDir, "orchestrator.lock"))
	// [TEMPORARY: Render deployment constraint]
	// If a previous run failed during Phase 1 (Ingestion), reset phase_checkpoint.json
	// and any corrupt normalized_bill.csv so Phase 1 starts completely fresh with clean DuckDB state.
	chkPath := filepath.Join(jobDir, "phase_checkpoint.json")
	if data, err := os.ReadFile(chkPath); err == nil {
		if strings.Contains(string(data), `"phase": 1`) || strings.Contains(string(data), `"phase":1`) {
			_ = os.Remove(chkPath)
			_ = os.Remove(filepath.Join(jobDir, "projection-audit", "normalized_bill.csv"))
			_ = os.Remove(filepath.Join(jobDir, "projection-audit", "projection.duckdb"))
		}
	}

	newSession := uuid.New().String()
	if err := h.db.ResetJobForRetry(id, newSession); err != nil {
		http.Error(w, `{"error":"db reset failed"}`, http.StatusInternalServerError)
		return
	}

	pid, assumptionsVersion, err := h.spawner.Start(jobDir, job.InputExt, newSession, job.Engine)
	if err != nil {
		h.db.UpdateJobFailed(id, "retry spawn failed: "+err.Error())
		// Issue 2: err.Error() can contain quotes/newlines — don't embed in JSON string
		http.Error(w, `{"error":"spawn failed"}`, http.StatusInternalServerError)
		return
	}
	if assumptionsVersion != "" {
		_ = h.db.UpdateJobAssumptionsVersion(id, assumptionsVersion)
	}
	if err := h.db.UpdateJobPID(id, pid); err != nil {
		slog.Error("UpdateJobPID failed after Retry", "job_id", id, "pid", pid, "err", err)
	}
	h.db.UpdateJobRunning(id)
	go h.watcher.Watch(id, pid)

	w.Header().Set(contentTypeHeader, contentTypeJSON)
	w.WriteHeader(http.StatusAccepted)
	json.NewEncoder(w).Encode(map[string]any{"id": id, "status": "running", "pid": pid})
}

// RegenerateReport re-runs render_report.py for a finished job using the
// current report settings. The previous report is preserved.
func (h *Handler) RegenerateReport(w http.ResponseWriter, r *http.Request) {
	sess := auth.SessionFromCtx(r.Context())
	id := chi.URLParam(r, "id")
	if !isValidJobID(id) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	job, err := h.db.GetJob(id)
	if err != nil {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if !h.canAccess(sess, job) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if job.Status != "done" {
		http.Error(w, `{"error":"can only regenerate a completed job"}`, http.StatusConflict)
		return
	}

	jobDir := filepath.Clean(filepath.Join(h.jobsDir, id))
	h.ensureJobDirRestored(r.Context(), id, jobDir)

	// One at a time per job.
	regenLocks.mu.Lock()
	if regenLocks.m[id] {
		regenLocks.mu.Unlock()
		http.Error(w, `{"error":"report regeneration already in progress for this job"}`, http.StatusConflict)
		return
	}
	regenLocks.m[id] = true
	defer func() {
		regenLocks.mu.Lock()
		delete(regenLocks.m, id)
		regenLocks.mu.Unlock()
	}()

	// Check that projection.duckdb exists.
	dbPath := filepath.Join(jobDir, projectionAuditDir, projectionDuckDB)
	if _, err := os.Stat(dbPath); os.IsNotExist(err) {
		http.Error(w, `{"error":"job has no projection data; cannot regenerate report"}`, http.StatusBadRequest)
		return
	}

	// Write report-settings.json from current DB values.
	settings, err := h.db.GetReportSettings()
	if err != nil {
		http.Error(w, `{"error":"db error"}`, http.StatusInternalServerError)
		return
	}
	if settings == nil {
		settings = []*db.ReportSetting{}
	}
	values := make(map[string]string, len(settings))
	for _, s := range settings {
		values[s.Key] = s.Value
	}
	version, err := h.db.ReportSettingsVersionHash()
	if err != nil {
		http.Error(w, `{"error":"db error"}`, http.StatusInternalServerError)
		return
	}
	values["__version__"] = version
	snapshot := map[string]any{
		"version":      version,
		"generated_at": time.Now().UTC().Format(time.RFC3339),
		"values":       values,
	}
	snapshotJSON, err := json.Marshal(snapshot)
	if err != nil {
		http.Error(w, `{"error":"failed to build settings snapshot"}`, http.StatusInternalServerError)
		return
	}
	if err := os.WriteFile(filepath.Join(jobDir, "report-settings.json"), append(snapshotJSON, '\n'), 0644); err != nil {
		http.Error(w, `{"error":"failed to write settings snapshot"}`, http.StatusInternalServerError)
		return
	}

	// Run only render_report.py, with CWD set to the job directory.
	python := pythonBin()
	scriptsDir := filepath.Join(skill.ResolveDir(), "scripts")
	scriptPath := filepath.Join(scriptsDir, "render_report.py")
	cmd := exec.Command(python, scriptPath)
	cmd.Dir = jobDir
	cmd.Env = append(os.Environ(),
		"SKILL_DIR="+skill.ResolveDir(),
		"PYTHONPATH="+scriptsDir,
	)
	logFilePath := filepath.Join(jobDir, "regenerate.log")
	logFile, err := os.OpenFile(logFilePath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		http.Error(w, `{"error":"could not open regenerate log"}`, http.StatusInternalServerError)
		return
	}
	defer logFile.Close()
	cmd.Stdout = logFile
	cmd.Stderr = logFile

	if err := cmd.Run(); err != nil {
		slog.Error("regenerate report failed", "job_id", id, "err", err)
		http.Error(w, `{"error":"report regeneration failed"}`, http.StatusInternalServerError)
		return
	}

	// Record in audit log.
	changedBy := ""
	if sess != nil && sess.Email != "" {
		changedBy = sess.Email
	}
	_ = h.db.LogAdminAction(changedBy, "regenerate_report", id, version)

	w.Header().Set(contentTypeHeader, contentTypeJSON)
	json.NewEncoder(w).Encode(map[string]any{
		"id":      id,
		"run_id":  version,
		"status":  "regenerated",
		"version": version,
	})
}

func (h *Handler) Refine(w http.ResponseWriter, r *http.Request) {
	sess := auth.SessionFromCtx(r.Context())
	id := chi.URLParam(r, "id")
	if !isValidJobID(id) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	job, err := h.db.GetJob(id)
	if err != nil {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if !h.canAccess(sess, job) {
		http.Error(w, `{"error":"not found"}`, http.StatusNotFound)
		return
	}
	if job.Status != "done" {
		http.Error(w, `{"error":"can only refine a completed job"}`, http.StatusConflict)
		return
	}
	if job.SessionID == "" {
		http.Error(w, `{"error":"job has no session_id; cannot resume"}`, http.StatusConflict)
		return
	}
	var body struct {
		Instruction string `json:"instruction"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		http.Error(w, `{"error":"invalid json"}`, http.StatusBadRequest)
		return
	}
	if len(body.Instruction) < 3 || len(body.Instruction) > 10000 {
		http.Error(w, `{"error":"instruction must be 3-10000 characters"}`, http.StatusBadRequest)
		return
	}

	jobDir := filepath.Clean(filepath.Join(h.jobsDir, id))
	h.ensureJobDirRestored(r.Context(), id, jobDir)
	// Issue 8: set running BEFORE spawning so any concurrent poll sees 'running'
	if err := h.db.UpdateJobRunning(id); err != nil {
		http.Error(w, `{"error":"db error"}`, http.StatusInternalServerError)
		return
	}
	pid, err := h.spawner.StartRefine(jobDir, job.SessionID, body.Instruction)
	if err != nil {
		h.db.UpdateJobFailed(id, "refine spawn failed: "+err.Error())
		// Issue 2: err.Error() can contain quotes/newlines — don't embed in JSON string
		http.Error(w, `{"error":"spawn failed"}`, http.StatusInternalServerError)
		return
	}
	// Issue 4: check and log UpdateJobPID errors; non-fatal since watcher still fires
	if err := h.db.UpdateJobPID(id, pid); err != nil {
		slog.Error("UpdateJobPID failed after StartRefine", "job_id", id, "pid", pid, "err", err)
	}
	go h.watcher.WatchOnce(id, pid)

	w.Header().Set(contentTypeHeader, contentTypeJSON)
	w.WriteHeader(http.StatusAccepted)
	json.NewEncoder(w).Encode(map[string]any{"id": id, "status": "refining", "pid": pid})
}

