#!/usr/bin/env python3
"""
refresh_ec2_specs.py [--region us-east-1] [--offline <index.json>]

Regenerate data/ec2-instance-types.json — the local, authoritative EC2 instance
spec table (instance_type -> vcpus, ram_gb, arch, chip) that ingest uses to size
GCP equivalents when the bill gives an instance type but not its specs.

Why a local table (not a live API call per bill)
------------------------------------------------
The per-bill pipeline must stay deterministic and offline (it only shells out to
`agy`). So specs come from a table committed to the repo, regenerated by this
maintenance script from AWS's own public Price List — exactly the pattern of
scripts/refresh_aws_product_codes.py. The one network call lives here, run
occasionally, never in the hot path.

Source
------
AWS Price List bulk API, EC2 offer, one region's file (all instance types appear
in us-east-1). The file is large (~480 MB), so it is STREAM-parsed with ijson at
constant memory. Only `Compute Instance` products are read; specs are identical
across regions, so one region is sufficient.

ijson is required for this maintenance script only (`pip install ijson`); the
per-bill pipeline does not import it.

Usage
-----
    python3 refresh_ec2_specs.py                 # pull us-east-1 from AWS
    python3 refresh_ec2_specs.py --region eu-west-1
    python3 refresh_ec2_specs.py --offline path/to/us-east-1/index.json
"""
from __future__ import annotations

import datetime as _dt
import json
import os
import re
import sys
import urllib.request

_HERE = os.path.dirname(os.path.abspath(__file__))
_OUT = os.path.join(_HERE, "..", "data", "ec2-instance-types.json")
_BASE = "https://pricing.us-east-1.amazonaws.com"
_REGION_INDEX = _BASE + "/offers/v1.0/aws/AmazonEC2/current/region_index.json"

_MEM_RE = re.compile(r"([\d,.]+)\s*GiB", re.IGNORECASE)


def _region_file_url(region: str) -> str:
    req = urllib.request.Request(_REGION_INDEX, headers={"User-Agent": "refresh-ec2-specs"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        idx = json.loads(resp.read())
    regions = idx.get("regions", {})
    r = regions.get(region) or regions.get("us-east-1") or next(iter(regions.values()))
    return _BASE + r["currentVersionUrl"]


def _arch_of(phys: str) -> str:
    return "arm64" if "graviton" in (phys or "").lower() else "x86_64"


def _parse_memory(mem: str) -> float | None:
    if not mem:
        return None
    m = _MEM_RE.search(mem)
    if not m:
        return None
    try:
        return float(m.group(1).replace(",", ""))
    except ValueError:
        return None


def _stream_products(fh):
    """Yield each product dict from the price-list JSON's "products" map."""
    import ijson
    for _sku, product in ijson.kvitems(fh, "products"):
        yield product


def build(region: str = "us-east-1", offline: str | None = None) -> dict:
    specs: dict[str, dict] = {}
    seen = 0

    def consume(fh):
        nonlocal seen
        for product in _stream_products(fh):
            if product.get("productFamily") != "Compute Instance":
                continue
            attr = product.get("attributes", {})
            itype = attr.get("instanceType")
            vcpu = attr.get("vcpu")
            ram = _parse_memory(attr.get("memory", ""))
            if not itype or not vcpu or ram is None:
                continue
            try:
                vcpus = int(float(vcpu))
            except ValueError:
                continue
            # First spec wins; specs are identical across OS/tenancy variants.
            if itype not in specs:
                specs[itype] = {
                    "vcpus": vcpus,
                    "ram_gb": ram,
                    "arch": _arch_of(attr.get("physicalProcessor", "")),
                    "chip": attr.get("physicalProcessor", "") or None,
                }
                seen += 1

    if offline:
        with open(offline, "rb") as fh:
            consume(fh)
    else:
        url = _region_file_url(region)
        print(f"refresh_ec2_specs: streaming {url}", file=sys.stderr)
        req = urllib.request.Request(url, headers={"User-Agent": "refresh-ec2-specs"})
        with urllib.request.urlopen(req, timeout=600) as resp:
            consume(resp)

    return specs


def main() -> int:
    region, offline = "us-east-1", None
    args = sys.argv[1:]
    i = 0
    while i < len(args):
        if args[i] == "--region" and i + 1 < len(args):
            region = args[i + 1]; i += 2
        elif args[i] == "--offline" and i + 1 < len(args):
            offline = args[i + 1]; i += 2
        else:
            i += 1

    try:
        fresh = build(region, offline)
    except Exception as exc:  # pragma: no cover - network/parse failure
        print(f"refresh_ec2_specs: failed ({exc})", file=sys.stderr)
        return 1

    if not fresh:
        print("refresh_ec2_specs: no specs parsed — aborting (kept existing table)", file=sys.stderr)
        return 1

    # Merge onto the existing table, preserving its metadata keys (leading "_").
    try:
        existing = json.load(open(_OUT, encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        existing = {}
    meta = {k: v for k, v in existing.items() if k.startswith("_")}
    added = sum(1 for k in fresh if k not in existing)
    merged = {**{k: v for k, v in existing.items() if not k.startswith("_")}, **fresh}

    out = {
        "_note": ("AWS EC2 instance type specifications (instance_type -> vcpus, "
                  "ram_gb, arch, chip). Generated by scripts/refresh_ec2_specs.py "
                  "from the AWS Price List; used by ingest for GCP sizing."),
        "_source": _REGION_INDEX,
        "_generated": _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "_count": len(merged),
        **dict(sorted(merged.items())),
    }
    # Keep any other pre-existing metadata keys we didn't overwrite.
    for k, v in meta.items():
        out.setdefault(k, v)

    with open(_OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, ensure_ascii=False)
        fh.write("\n")

    print(f"refresh_ec2_specs: wrote {len(merged)} instance types "
          f"({added} new) to {os.path.relpath(_OUT, _HERE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
