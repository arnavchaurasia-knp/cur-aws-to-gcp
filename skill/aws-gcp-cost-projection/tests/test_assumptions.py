def test_every_default_key_referenced_in_scripts():
    """Ratchet: every key in assumption-defaults.json must be referenced in scripts/*.py."""
    data_dir = os.path.join(os.path.dirname(__file__), "..", "data")
    defaults_path = os.path.join(data_dir, "assumption-defaults.json")
    with open(defaults_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    keys = list(data.get("values", {}).keys())
    assert keys, "assumption-defaults.json has no keys"

    scripts_dir = os.path.join(os.path.dirname(__file__), "..", "scripts")
    script_files = [
        os.path.join(scripts_dir, fname)
        for fname in os.listdir(scripts_dir)
        if fname.endswith(".py")
    ]

    all_script_text = ""
    for sf in script_files:
        with open(sf, "r", encoding="utf-8", errors="replace") as f:
            all_script_text += f.read() + "\n"

    unreferenced = [k for k in keys if k not in all_script_text]
    assert not unreferenced, (
        f"Found unreferenced assumption keys in data/assumption-defaults.json: {unreferenced}. "
        "Every default key must be wired to at least one reference in scripts/*.py."
    )


def test_pipeline_stage_produces_different_cost_under_job_override():
    """load_assumptions(job_dir) reads user overrides and pipeline stage produces different $."""
    import duckdb
    from ingest import apply_od_basis

    with tempfile.TemporaryDirectory() as job_dir:
        # Baseline run with defaults
        conn1 = duckdb.connect(":memory:")
        conn1.execute("CREATE TABLE aws_li_catalog (aws_li_key VARCHAR, product VARCHAR, pricing_model VARCHAR, line_item_type VARCHAR, aws_amortized_cost DOUBLE, pricing_unit VARCHAR)")
        conn1.execute("INSERT INTO aws_li_catalog VALUES ('k1', 'AmazonEC2', 'Spot', 'Usage', 30.0, 'Hrs')")
        baseline_assumptions = load_assumptions(None)
        apply_od_basis(conn1, assumptions=baseline_assumptions)
        cost_baseline = conn1.execute("SELECT aws_od_cost FROM aws_li_catalog WHERE aws_li_key='k1'").fetchone()[0]

        # Write assumptions.json with custom override as generated by RerunJobAssumptions
        merged_values = dict(baseline_assumptions)
        merged_values["aws_spot_discount_pct"] = 0.85
        snapshot = {
            "version": "v1-custom-999",
            "overridden_keys": ["aws_spot_discount_pct"],
            "values": merged_values,
        }
        with open(os.path.join(job_dir, "assumptions.json"), "w", encoding="utf-8") as f:
            json.dump(snapshot, f)

        # Overridden run
        conn2 = duckdb.connect(":memory:")
        conn2.execute("CREATE TABLE aws_li_catalog (aws_li_key VARCHAR, product VARCHAR, pricing_model VARCHAR, line_item_type VARCHAR, aws_amortized_cost DOUBLE, pricing_unit VARCHAR)")
        conn2.execute("INSERT INTO aws_li_catalog VALUES ('k1', 'AmazonEC2', 'Spot', 'Usage', 30.0, 'Hrs')")
        overridden_assumptions = load_assumptions(job_dir)
        assert overridden_assumptions["aws_spot_discount_pct"] == 0.85

        apply_od_basis(conn2, assumptions=overridden_assumptions)
        cost_overridden = conn2.execute("SELECT aws_od_cost FROM aws_li_catalog WHERE aws_li_key='k1'").fetchone()[0]

        # With 70% spot discount, $30 spot usage reconstructs to $100 OD basis.
        # With 85% spot discount, $30 spot usage reconstructs to $200 OD basis.
        assert round(cost_baseline, 2) == 100.00
        assert round(cost_overridden, 2) == 200.00
        assert cost_overridden != cost_baseline


def test_load_assumptions_rejects_out_of_band_ratio():
    """load_assumptions(job_dir) falls back to defaults when stored ratio is out of band."""
